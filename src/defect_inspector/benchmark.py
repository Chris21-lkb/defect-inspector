"""Run several models on several categories and build a results table.

Two sub-commands:

    python -m defect_inspector.benchmark run      # trains every model/category pair
    python -m defect_inspector.benchmark report   # builds docs/results.md from saved metrics

``run`` can take a long time (it downloads data and trains each pair), so
``report`` is separate: it only reads the ``metrics.json`` files that
``train.py`` already wrote and does not need a GPU.
"""

import argparse
import json
from pathlib import Path

from defect_inspector import train
from defect_inspector.train import MODELS

# Categories closest to connector / electronic-part inspection.
DEFAULT_CATEGORIES = ["cable", "transistor", "metal_nut"]


def run_all(models: list[str], categories: list[str], results_dir: str, data_root: str, batch_size: int, num_workers: int) -> None:
    """Train and evaluate every model/category combination."""
    for category in categories:
        for model in models:
            print(f"\n=== {model} on {category} ===")
            args = argparse.Namespace(
                model=model,
                category=category,
                data_root=data_root,
                results_dir=results_dir,
                batch_size=batch_size,
                num_workers=num_workers,
            )
            train.run(args)


def build_report(results_dir: str, output: str) -> None:
    """Collect all metrics.json files into one Markdown table."""
    records = []
    for path in sorted(Path(results_dir).glob("*/*/metrics.json")):
        with open(path, encoding="utf-8") as f:
            records.append(json.load(f))

    if not records:
        raise SystemExit(f"No metrics.json files found under {results_dir}/. Run training first.")

    # Metric names come from anomalib, so build the columns from what is present.
    metric_names = sorted({name for r in records for name in r["metrics"]})

    header = ["Model", "Category", *metric_names, "Train time (s)", "Peak GPU mem (MB)", "Device"]
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    for r in records:
        row = [r["model"], r["category"]]
        row += [f"{r['metrics'][m]:.3f}" if m in r["metrics"] else "-" for m in metric_names]
        row += [str(r["train_seconds"]), str(r["peak_gpu_memory_mb"]), r["device"]]
        lines.append("| " + " | ".join(row) + " |")

    out = Path(output)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("# Benchmark results\n\nGenerated by `defect_inspector.benchmark report`.\n\n" + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {out}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = parser.add_subparsers(dest="command", required=True)

    run_p = sub.add_parser("run", help="Train every model/category pair")
    run_p.add_argument("--models", nargs="+", default=sorted(MODELS), choices=sorted(MODELS))
    run_p.add_argument("--categories", nargs="+", default=DEFAULT_CATEGORIES)
    run_p.add_argument("--results-dir", default="results")
    run_p.add_argument("--data-root", default="datasets/MVTecAD")
    run_p.add_argument("--batch-size", type=int, default=16)
    run_p.add_argument("--num-workers", type=int, default=4)

    rep_p = sub.add_parser("report", help="Build docs/results.md from saved metrics")
    rep_p.add_argument("--results-dir", default="results")
    rep_p.add_argument("--output", default="docs/results.md")

    args = parser.parse_args()
    if args.command == "run":
        run_all(args.models, args.categories, args.results_dir, args.data_root, args.batch_size, args.num_workers)
    else:
        build_report(args.results_dir, args.output)


if __name__ == "__main__":
    main()
